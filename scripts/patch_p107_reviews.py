import urllib.request
import io
import re
from PIL import Image

# 1. Download & Crop
jobs = [
    ("https://http2.mlstatic.com/D_NQ_NP_900270-MLA106278928463_012026-F.jpg", "img/review-107-real-1.jpg"),
    ("https://http2.mlstatic.com/D_NQ_NP_916151-MLA84878220839_052025-F.jpg", "img/review-107-real-2.jpg"),
    ("https://http2.mlstatic.com/D_NQ_NP_684778-MLA88692591324_072025-F.jpg", "img/review-107-real-3.jpg"),
    ("https://http2.mlstatic.com/D_NQ_NP_995649-MLA95659461711_102025-F.jpg", "img/review-107-real-4.jpg"),
]

for url, dest in jobs:
    print(f"Downloading {url} -> {dest}")
    data = urllib.request.urlopen(url).read()
    im = Image.open(io.BytesIO(data)).convert('RGB')
    w, h = im.size
    min_dim = min(w, h)
    left = (w - min_dim) // 2
    top = (h - min_dim) // 2
    im_c = im.crop((left, top, left + min_dim, top + min_dim)).resize((600, 600), Image.Resampling.LANCZOS)
    im_c.save(dest, 'JPEG', quality=88)
    print(f"[OK] {dest} (600x600)")

